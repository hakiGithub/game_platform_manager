def blob(ref):
    return subprocess.run(["git", "show", f"{ref}:{DOC}"], capture_output=True, check=True)\
        .stdout.decode("utf-8").replace("\r\n", "\n")


def save(text):
    with open(OUT, "wb") as f:
        f.write(text.encode("utf-8"))


def main():
    which = ALLX if "--phase2" in sys.argv or "--rebuild" in sys.argv else PHASE1
    if "--check-only" in sys.argv:
        t = open(OUT, encoding="utf-8").read().replace("\r\n", "\n")
        for i, (o, n) in enumerate(ALLX, 1):
            print(f"T{i:2d} cand_old={t.count(o)} parent_old={blob(OLD_REF).count(o)} new_len={len(n)}  {o[:40]!r}")
        return
    if "--rebuild" in sys.argv:
        text = blob(OLD_REF)
        for i, (o, n) in enumerate(which, 1):
            assert text.count(o) == 1, f"T{i} 旧串命中 {text.count(o)} 次（须恰 1 次）: {o[:70]!r}"
            text = text.replace(o, n, 1)
        save(text)
        print(f"rebuilt from {OLD_REF} + {len(which)} authorized replacements -> {OUT}")
        return
    raise SystemExit("用法: --rebuild [--phase2] | --check-only")


if __name__ == "__main__":
    main()
